"""Generates crates/gadk-gemini/tests/inventory.rs from docs/parity/genai-inventory.md (R2)."""
import pathlib, re, subprocess
repo = pathlib.Path(__file__).resolve().parent.parent
rows = [l for l in (repo / "docs/parity/genai-inventory.md").read_text().splitlines() if l.startswith("| ") and not l.startswith("| genai identifier")]
CALLS = {
    "gadk_genai::text": 'gadk_genai::text("t")',
    "gadk_genai::Content::from_text": 'gadk_genai::Content::from_text("t", "user")',
    "gadk_genai::Content::from_parts": 'gadk_genai::Content::from_parts(vec![], "user")',
    "gadk_genai::Content::from_function_call": 'gadk_genai::Content::from_function_call(Default::default(), "model")',
    "gadk_genai::Content::from_function_response": 'gadk_genai::Content::from_function_response(Default::default(), "user")',
    "gadk_genai::Content::from_bytes": 'gadk_genai::Content::from_bytes(bytes::Bytes::new(), "image/png", "user")',
    "gadk_genai::Content::from_uri": 'gadk_genai::Content::from_uri("gs://b/o", "image/png", "user")',
    "gadk_genai::Content::from_executable_code": 'gadk_genai::Content::from_executable_code("print(1)", gadk_genai::Language::Python, "model")',
    "gadk_genai::Content::from_code_execution_result": 'gadk_genai::Content::from_code_execution_result(gadk_genai::Outcome::Ok, "1", "model")',
    "gadk_genai::Part::from_text": 'gadk_genai::Part::from_text("t")',
    "gadk_genai::Part::from_bytes": 'gadk_genai::Part::from_bytes(bytes::Bytes::new(), "image/png")',
    "gadk_genai::Part::from_uri": 'gadk_genai::Part::from_uri("gs://b/o", "image/png")',
    "gadk_genai::Part::from_file": 'gadk_genai::Part::from_file(&gadk_genai::File::default())',
    "gadk_genai::Part::from_function_call": 'gadk_genai::Part::from_function_call("f", Default::default())',
    "gadk_genai::Part::from_function_response": 'gadk_genai::Part::from_function_response("f", Default::default())',
    "gadk_genai::Part::from_executable_code": 'gadk_genai::Part::from_executable_code("x", gadk_genai::Language::Python)',
    "gadk_genai::Part::from_code_execution_result": 'gadk_genai::Part::from_code_execution_result(gadk_genai::Outcome::Ok, "1")',
    "gadk_gemini::GeminiModel::new": 'gadk_gemini::GeminiModel::new("m", Default::default())',
}
lines = ["// Generated by scripts/gen-inventory-test.py — do not edit.", "#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]", "#![allow(unused_imports, dead_code, clippy::no_effect)]", ""]
lines.append("#[test]\nfn inventory_paths_exist() {")
for r in rows:
    cells = [c.strip() for c in r.strip("|").split("|")]
    ident, kind, path = cells[0], cells[1], cells[2]
    p = path.split(" ")[0]
    if p == "gadk_gemini::GeminiModel" and "folded" in path:
        p = "gadk_gemini::GeminiModel"
    if not p.startswith("gadk_"):
        continue
    if kind == "enum value" or (kind == "client" and "::Backend::" in p) or kind == "const":
        lines.append(f"    let _ = {p};")
    elif p in CALLS:
        # never-called closure: type-checks the call without fn-pointer inference (impl Trait args)
        lines.append(f"    let _ = || {CALLS[p]};")
    elif kind == "client" and "ModelError::Api" in p:
        lines.append("    let _ = |e: gadk_model::ModelError| matches!(e, gadk_model::ModelError::Api { .. });")
    else:
        lines.append(f"    let _ = std::mem::size_of::<Option<{p}>>();")
lines.append("}")
header = (repo / "crates/gadk-genai/src/lib.rs").read_text().split("\n\n", 1)[0] + "\n\n"  # HEADER block written in Task 1
out = repo / "crates/gadk-gemini/tests/inventory.rs"
out.write_text(header + "\n".join(lines) + "\n")
# keep the committed file `cargo fmt --all --check` clean (rustfmt picks up the repo's rustfmt config)
subprocess.run(["rustfmt", "--edition", "2024", str(out)], check=True)
