class Repo:
    def __init__(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self._tmp.name)

    def write(self, rel, text):
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(text), encoding="utf-8")

    def hits(self):
        return [(p, n) for p, n, _ in refs.scan(self.root)]

    def check(self):
        return refs.check(self.root)

    def close(self):
        self._tmp.cleanup()


class LexTest(unittest.TestCase):
    def kinds(self, src):
        return [(k, src[s:e]) for k, s, e in rust_lex.segments(src) if k != "code"]

    def test_nested_block_comment(self):
        self.assertEqual(self.kinds("a /* x /* y */ z */ b"), [("comment", "/* x /* y */ z */")])

    def test_raw_string_with_slashes_and_quotes(self):
        src = 'let s = r#"a // "b" c"#; // tail'
        self.assertEqual(self.kinds(src), [("str", 'r#"a // "b" c"#'), ("comment", "// tail")])

    def test_raw_identifier_is_code(self):
        self.assertEqual(self.kinds("let r#type = 1; // c"), [("comment", "// c")])

    def test_byte_string_and_raw_byte_string(self):
        src = 'f(b"//x", br"//y", b\'"\')'
        self.assertEqual(self.kinds(src), [("str", 'b"//x"'), ("str", 'br"//y"'), ("str", "b'\"'")])

    def test_char_quote_and_lifetime(self):
        src = "fn f<'a>(x: &'a str) -> char { '\"' } // c"
        self.assertEqual(self.kinds(src), [("str", "'\"'"), ("comment", "// c")])

    def test_escaped_quote_in_string(self):
        self.assertEqual(self.kinds('"a\\"// b" // c'), [("str", '"a\\"// b"'), ("comment", "// c")])

    def test_unterminated_block_comment_raises(self):
        with self.assertRaises(rust_lex.LexError):
            rust_lex.segments("/* open")


class ScanTest(unittest.TestCase):
    def setUp(self):
        self.r = Repo()

    def tearDown(self):
        self.r.close()

    def test_reports_doc_plain_block_readme_and_toml(self):
        self.r.write("crates/c/src/lib.rs", """\
            /// Port of Go `x`.
            pub fn x() {}
            // like Go does
            /* Go text */
            fn y() {}
        """)
        self.r.write("crates/c/README.md", "A port of ADK-Go.\n")
        self.r.write("README.md", "clean\nGo here\n")
        self.r.write("crates/c/Cargo.toml", '[package]\nname = "c" # Go name\n')
        self.assertEqual(sorted(self.r.hits()), [
            ("README.md", 2), ("crates/c/Cargo.toml", 2), ("crates/c/README.md", 1),
            ("crates/c/src/lib.rs", 1), ("crates/c/src/lib.rs", 3), ("crates/c/src/lib.rs", 4),
        ])

    def test_package_qualified_names(self):
        self.r.write("crates/c/src/lib.rs", """\
            /// Shape of `genai.Part`.
            /// A `time.Duration` value.
            /// Like `google.rpc.Status`.
            /// Published on crates.io.
            /// See [`Part`] and `Self::new`.
            fn f() {}
        """)
        self.assertEqual(
            sorted(self.r.hits()), [("crates/c/src/lib.rs", 1), ("crates/c/src/lib.rs", 2)]
        )

    def test_string_literal_not_scanned(self):
        self.r.write("crates/c/src/lib.rs", 'const A: &str = "google.golang.org/adk/v2 Go";\n')
        self.assertEqual(self.r.hits(), [])

    def test_licence_headers_skipped(self):
        self.r.write("crates/c/src/lib.rs", APACHE + "\n// Go note\n")
        self.r.write("crates/c/src/m.rs", MIT + "\n/// Go doc\nfn f() {}\n")
        self.assertEqual(sorted(self.r.hits()), [("crates/c/src/lib.rs", 7), ("crates/c/src/m.rs", 6)])

    def test_skip_dirs_and_generated(self):
        self.r.write("crates/c/src/parity_tests/a.rs", "// Go\n")
        self.r.write("crates/c/tests/b.rs", "// Go\n")
        self.r.write("crates/c/src/gen.rs", "// @generated by prost\n// Go package\n")
        self.assertEqual(self.r.hits(), [])

    def test_inline_test_modules(self):
        self.r.write("crates/c/src/lib.rs", """\
            #[cfg(test)]
            mod tests {
                // Go inside test
                fn f() { let s = "}"; }
            }
            #[cfg(all(test, unix))]
            #[allow(clippy::unwrap_used)]
            /// docs between
            pub(crate) mod unix_tests {
                // Go unix
            }
            #[cfg(any(test, feature = "x"))]
            mod shipped {
                // Go shipped
            }
            // Go after
        """)
        self.assertEqual(self.r.hits(), [("crates/c/src/lib.rs", 14), ("crates/c/src/lib.rs", 16)])

    def test_file_test_modules_resolution(self):
        self.r.write("crates/c/src/lib.rs", "#[cfg(test)]\nmod a;\nmod foo;\nmod d;\n")
        self.r.write("crates/c/src/a.rs", "// Go a\nmod inner;\n")
        self.r.write("crates/c/src/a/inner.rs", "// Go a inner\n")
        self.r.write("crates/c/src/foo.rs", "#[cfg(test)]\nmod b;\n#[cfg(test)]\n#[path = \"x_tests.rs\"]\nmod x;\n")
        self.r.write("crates/c/src/foo/b.rs", "// Go b\n")
        self.r.write("crates/c/src/x_tests.rs", "// Go x\n")
        self.r.write("crates/c/src/d/mod.rs", "#[cfg(test)]\nmod e;\n// Go d\n")
        self.r.write("crates/c/src/d/e.rs", "// Go e\n")
        self.assertEqual(self.r.hits(), [("crates/c/src/d/mod.rs", 3)])

    def test_unresolvable_test_module_is_error(self):
        self.r.write("crates/c/src/lib.rs", "#[cfg(test)]\nmod missing;\n")
        problems, code = self.r.check()
        self.assertEqual(code, 2)
        self.assertIn("missing", problems[0])

    def test_allowlist(self):
        self.r.write("crates/c/src/lib.rs", "//! Wire-compatible with ADK-Go servers.\n// Go a\n// Go b\n")
        self.r.write("scripts/go-refs-allow/c.txt",
                     "# comment\ncrates/c/src/lib.rs\tWire-compatible\tcompat note\n")
        problems, code = self.r.check()
        self.assertEqual(code, 1)
        self.assertEqual(problems, ["crates/c/src/lib.rs:2: // Go a", "crates/c/src/lib.rs:3: // Go b"])

    def test_allowlist_stale_or_broad(self):
        self.r.write("crates/c/src/lib.rs", "// Go a\n// Go b\n")
        self.r.write("scripts/go-refs-allow/c.txt",
                     "crates/c/src/lib.rs\tGo\ttoo broad\ncrates/c/src/lib.rs\tnothing\tstale\n")
        problems, code = self.r.check()
        self.assertEqual(code, 1)
        self.assertTrue(any("matches 2 hit lines" in p for p in problems))
        self.assertTrue(any("matches no hit line" in p for p in problems))

    def test_allowlist_limit_and_wrong_file(self):
        self.r.write("crates/c/src/lib.rs", "// Go 1\n// Go 2\n// Go 3\n// Go 4\n")
        self.r.write("README.md", "Go\n")
        self.r.write("scripts/go-refs-allow/c.txt", "".join(
            f"crates/c/src/lib.rs\tGo {i}\tr\n" for i in range(1, 5)) + "README.md\tGo\tr\n")
        problems, code = self.r.check()
        self.assertEqual(code, 1)
        self.assertIn("scripts/go-refs-allow/c.txt: 5 entries, limit 3", problems)
        self.assertIn("scripts/go-refs-allow/c.txt:5: path 'README.md' does not belong in c.txt", problems)

    def test_paths_filter(self):
        self.r.write("crates/a/src/lib.rs", "// Go a\n")
        self.r.write("crates/b/src/lib.rs", "// Go b\n")
        self.assertEqual(refs.check(self.r.root, ["crates/b/"]), (["crates/b/src/lib.rs:1: // Go b"], 1))

    def test_clean_repo_exits_zero(self):
        self.r.write("crates/c/src/lib.rs", "/// Returns the sum.\npub fn f() {}\n")
        self.assertEqual(self.r.check(), ([], 0))


class CommentOnlyTest(unittest.TestCase):
    def setUp(self):
        self.r = Repo()
        self.git("init", "-q")
        self.git("config", "user.email", "t@example.com")
        self.git("config", "user.name", "t")
        self.r.write("crates/c/src/lib.rs", '/// Go `f`.\npub fn f() -> &\'static str { "a  b" }\n')
        self.r.write("crates/c/Cargo.toml", '[package]\nname = "c" # Go\n')
        self.r.write("crates/c/src/prompt.md", "prompt\n")
        self.git("add", "-A")
        self.git("commit", "-qm", "base")

    def tearDown(self):
        self.r.close()

    def git(self, *args):
        subprocess.run(["git", "-C", str(self.r.root), *args], check=True)

    def problems(self):
        return only.check(self.r.root, "HEAD")

    def test_comment_and_doc_changes_pass(self):
        self.r.write("crates/c/src/lib.rs",
                     '/// Returns a constant.\n// note\npub fn f() -> &\'static str {   "a  b" }\n')
        self.r.write("crates/c/Cargo.toml", '[package]\n# crate c\nname = "c"\n')
        self.r.write("README.md", "anything\n")
        self.r.write("scripts/go-refs-allow/c.txt", "x\n")
        self.assertEqual(self.problems(), [])

    def test_code_or_literal_change_fails(self):
        self.r.write("crates/c/src/lib.rs", '/// Go `f`.\npub fn f() -> &\'static str { "a b" }\n')
        self.assertEqual(self.problems(), ["crates/c/src/lib.rs: code changed (not only comments)"])

    def test_exempt_path_literal_change_is_not_reported(self):
        from unittest import mock
        self.r.write("crates/c/tests/gen.rs", 'const A: &str = "a";\n')
        self.git("add", "-A")
        self.git("commit", "-qm", "gen")
        self.r.write("crates/c/tests/gen.rs", 'const A: &str = "b";\n')
        self.assertEqual(self.problems(), ["crates/c/tests/gen.rs: code changed (not only comments)"])
        with mock.patch.dict(only.CODE_EXEMPT, {"crates/c/tests/gen.rs": "test"}):
            self.assertEqual(self.problems(), [])

    def test_toml_value_change_fails(self):
        self.r.write("crates/c/Cargo.toml", '[package]\nname = "d" # Go\n')
        self.assertEqual(self.problems(), ["crates/c/Cargo.toml: non-comment change"])

    def test_hash_inside_escaped_string_is_not_a_comment(self):
        self.r.write("crates/c/Cargo.toml", '[package]\nname = "a \\"b\\" # c"\n')
        self.git("add", "-A")
        self.git("commit", "-qm", "q")
        self.r.write("crates/c/Cargo.toml", '[package]\nname = "a \\"b\\" # d"\n')
        self.assertEqual(self.problems(), ["crates/c/Cargo.toml: non-comment change"])

    def test_multiline_string_hash_is_not_a_comment(self):
        self.r.write("crates/c/Cargo.toml", '[package]\ndescription = """\nx # y\n"""\n')
        self.git("add", "-A")
        self.git("commit", "-qm", "m")
        self.r.write("crates/c/Cargo.toml", '[package]\ndescription = """\nx # z\n"""\n')
        self.assertEqual(self.problems(), ["crates/c/Cargo.toml: non-comment change"])
        self.r.write("crates/c/Cargo.toml", '[package]\ndescription = """\nx # y\n""" # note\n')
        self.assertEqual(self.problems(), [])

    def test_other_file_change_fails(self):
        self.r.write("crates/c/src/prompt.md", "changed\n")
        self.assertEqual(self.problems(), ["crates/c/src/prompt.md: file outside the comment-only scope changed"])

    def test_long_comment_line_fails(self):
        self.r.write("crates/c/src/lib.rs",
                     "/// " + "x" * 97 + "\npub fn f() -> &'static str { \"a  b\" }\n")
        self.assertEqual(self.problems(), ["crates/c/src/lib.rs:1: comment line is 101 > 100 characters"])


