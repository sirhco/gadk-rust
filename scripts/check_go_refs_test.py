import importlib.machinery, importlib.util, pathlib, subprocess, sys, tempfile, textwrap, unittest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import rust_lex  # noqa: E402


def _load(name, file):
    loader = importlib.machinery.SourceFileLoader(name, str(HERE / file))
    mod = importlib.util.module_from_spec(importlib.util.spec_from_loader(name, loader))
    loader.exec_module(mod)
    return mod


refs = _load("check_go_refs", "check-go-refs.py")
only = _load("check_comment_only", "check-comment-only.py")

