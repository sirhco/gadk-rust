import contextlib, importlib.machinery, importlib.util, io, json, pathlib, subprocess, sys, tempfile, unittest

HERE = pathlib.Path(__file__).resolve().parent
SCRIPT = HERE / "gen-console-client.py"
loader = importlib.machinery.SourceFileLoader("gen_console_client", str(SCRIPT))
spec = importlib.util.spec_from_loader("gen_console_client", loader)
gen = importlib.util.module_from_spec(spec)
loader.exec_module(gen)

REAL = gen.ROOT / gen.SPEC


def document(schemas, parameters=None, paths=None):
    """A minimal document with `schemas`, `parameters` and `paths`."""
    return {"openapi": "3.1.0", "paths": paths or {},
            "components": {"schemas": schemas, "parameters": parameters or {}}}


def obj(props, required=None, description="A thing."):
    """An object schema of `props` (all required unless `required` says otherwise)."""
    return {"type": "object", "description": description,
            "required": list(props) if required is None else required, "properties": props}


def prop(schema, description="A field."):
    return dict(schema, description=description)


def render(doc):
    """The unformatted Rust source of `doc`."""
    return gen.Gen(doc).render()


def op(op_id, params, schema_ref="#/components/schemas/Thing"):
    """A `get` operation with `params` (parameter names) answering `schema_ref`."""
    return {"get": {
        "operationId": op_id, "summary": "Some things", "description": "All of them.",
        "parameters": [{"$ref": f"#/components/parameters/{p}"} for p in params],
        "responses": {"200": {"description": "ok", "content": {"application/json": {
            "schema": {"$ref": schema_ref} if schema_ref else {"type": "object"}}}}}}}


THING = {"Thing": obj({"id": prop({"type": "string"})})}


def query_param(name, schema, description="A parameter."):
    return {"name": name, "in": "query", "required": False, "description": description,
            "schema": schema}


class RealDocumentTest(unittest.TestCase):
    def test_the_real_document_generates_byte_identical_output(self):
        doc = gen.load(REAL)
        first, second = gen.generate(doc), gen.generate(doc)
        self.assertEqual(first, second)
        self.assertTrue(first.startswith("// @generated by scripts/gen-console-client.py"))
        self.assertEqual(first.count("pub enum "), 2)
        self.assertIn("pub enum UsageRange {", first)
        self.assertIn("pub enum Range {", first)
        self.assertIn("pub struct ModelTokens(\n", first)
        self.assertIn("pub struct ApiErrorBody {", first)
        self.assertIn("pub error: ApiErrorBody,", first)
        self.assertNotIn("ApiErrorError", first)
        self.assertIn("    /// The model name.\n    pub String,\n", first)
        self.assertIn("    /// The model's token counts.\n    pub Usage,\n", first)
        self.assertIn("pub async fn get_open_api(", first)
        self.assertIn("Result<serde_json::Value, Error>", first)

    def test_check_passes_on_fresh_output_and_fails_on_edited_output(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = pathlib.Path(tmp) / "generated.rs"
            args = ["--spec", str(REAL), "--out", str(out)]
            self.assertEqual(gen.main(args), 0)
            self.assertEqual(gen.main(args + ["--check"]), 0)
            out.write_text(out.read_text() + "// edited\n")
            with contextlib.redirect_stderr(io.StringIO()) as err:
                self.assertEqual(gen.main(args + ["--check"]), 1)
                out.unlink()
                self.assertEqual(gen.main(args + ["--check"]), 1)
            self.assertEqual(err.getvalue().count("generated.rs is stale"), 2)

    def test_an_unreadable_check_target_or_an_unexpected_error_exits_2(self):
        with tempfile.TemporaryDirectory() as tmp:
            args = ["--spec", str(REAL), "--out", tmp, "--check"]  # the output is a directory
            with contextlib.redirect_stderr(io.StringIO()) as err:
                self.assertEqual(gen.main(args), 2)
            self.assertIn("gen-console-client:", err.getvalue())
            real = gen.generate
            def boom(doc):
                raise RuntimeError("boom")
            gen.generate = boom
            try:
                with contextlib.redirect_stderr(io.StringIO()) as err:
                    self.assertEqual(gen.main(["--spec", str(REAL), "--out",
                                               str(pathlib.Path(tmp) / "g.rs")]), 2)
            finally:
                gen.generate = real
            self.assertIn("boom", err.getvalue())

    def test_check_names_the_stale_file_on_stderr(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = pathlib.Path(tmp) / "generated.rs"
            out.write_text("// stale\n")
            r = subprocess.run([sys.executable, str(SCRIPT), "--check", "--spec", str(REAL),
                                "--out", str(out)], capture_output=True, text=True)
            self.assertEqual(r.returncode, 1)
            self.assertIn("generated.rs is stale", r.stderr)


class SchemaTest(unittest.TestCase):
    def test_all_of_flattens_member_fields_in_member_order(self):
        doc = document({
            "Row": obj({"b": prop({"type": "string"}), "a": prop({"type": "boolean"})}),
            "Cost": obj({"cost_usd": prop({"type": ["number", "null"]})}),
            "PricedRow": {"description": "A row with its cost.", "allOf": [
                {"$ref": "#/components/schemas/Row"}, {"$ref": "#/components/schemas/Cost"}]},
        })
        src = render(doc)
        priced = src[src.index("pub struct PricedRow {"):]
        priced = priced[:priced.index("}\n")]
        fields = [line.strip() for line in priced.split("\n") if line.strip().startswith("pub ")]
        self.assertEqual(fields[1:], ["pub b: String,", "pub a: bool,",
                                      "pub cost_usd: Option<f64>,"])
        self.assertIn("/// A row with its cost.\n#[derive(", src)

    def test_an_all_of_member_must_be_an_object_ref(self):
        doc = document({"Pair": {"type": "array", "description": "A pair.",
                                 "prefixItems": [{"type": "string"}], "items": False,
                                 "minItems": 1},
                        "Bad": {"description": "Bad.",
                                "allOf": [{"$ref": "#/components/schemas/Pair"}]}})
        with self.assertRaisesRegex(gen.GenError, "schema Bad: allOf member Pair"):
            render(doc)

    def test_nullable_and_non_required_fields_are_options(self):
        doc = document({"Thing": obj({
            "a": prop({"type": "string"}),
            "b": prop({"type": ["string", "null"]}),
            "c": prop({"type": "integer", "minimum": 0}),
        }, required=["a", "b"])})
        src = render(doc)
        self.assertIn("pub a: String,", src)
        self.assertIn("pub b: Option<String>,", src)
        self.assertIn("pub c: Option<u64>,", src)

    def test_the_type_mapping(self):
        doc = document({
            "Other": obj({"x": prop({"type": "boolean"})}),
            "Thing": obj({
                "at": prop({"type": "string", "format": "date-time"}),
                "end": prop({"type": ["string", "null"], "format": "date-time"}),
                "s": prop({"type": "string"}),
                "count": prop({"type": "integer", "minimum": 0}),
                "width": prop({"type": "integer", "minimum": 1}),
                "delta": prop({"type": "integer"}),
                "mean": prop({"type": "number"}),
                "ok": prop({"type": "boolean"}),
                "tags": prop({"type": "array", "items": {"type": "string"}}),
                "other": prop({"$ref": "#/components/schemas/Other"}),
                "others": prop({"type": "array", "items": {"$ref": "#/components/schemas/Other"}}),
                "inner": prop({"type": "object", "required": ["k"], "properties": {
                    "k": prop({"type": "string"}, "The key.")}}, "The inner part."),
            }),
        })
        src = render(doc)
        for field in ["pub at: chrono::DateTime<chrono::Utc>,",
                      "pub end: Option<chrono::DateTime<chrono::Utc>>,",
                      "pub s: String,", "pub count: u64,", "pub width: u64,",
                      "pub delta: i64,", "pub mean: f64,", "pub ok: bool,",
                      "pub tags: Vec<String>,", "pub other: Other,",
                      "pub others: Vec<Other>,", "pub inner: ThingInner,"]:
            self.assertIn(field, src)
        self.assertIn("/// The inner part.\n#[derive(", src)
        self.assertIn("pub struct ThingInner {\n    /// The key.\n    pub k: String,", src)
        self.assertIn("#[non_exhaustive]\npub struct Thing {", src)
        self.assertNotIn("fn new", src[:src.index("impl Client")])

    def test_a_prefix_items_tuple_is_a_tuple_struct(self):
        doc = document({
            "Usage": obj({"input": prop({"type": "integer", "minimum": 0})}),
            "ModelTokens": {"type": "array", "description": "[model, usage]: one model's tokens.",
                            "prefixItems": [{"type": "string", "description": "The model."},
                                            {"$ref": "#/components/schemas/Usage"}],
                            "items": False, "minItems": 2},
        })
        src = gen.generate(doc)
        self.assertIn("#[non_exhaustive]\npub struct ModelTokens(\n"
                      "    /// The model.\n"
                      "    pub String,\n"
                      "    /// Element 1.\n"
                      "    pub Usage,\n);", src)
        self.assertIn("#[derive(Debug, Clone, PartialEq, serde::Deserialize, serde::Serialize)]\n"
                      "#[non_exhaustive]\npub struct ModelTokens(", src)

    def test_an_unsupported_construct_fails_naming_the_schema(self):
        doc = document({"Thing": obj({"v": prop({"oneOf": [{"type": "string"}]})})})
        with self.assertRaisesRegex(gen.GenError, r"schema Thing\.v: unsupported keyword oneOf"):
            render(doc)
        with tempfile.TemporaryDirectory() as tmp:
            spec_file = pathlib.Path(tmp) / "openapi.json"
            spec_file.write_text(json.dumps(document({"Bad": {"oneOf": [], "description": "x"}})))
            r = subprocess.run([sys.executable, str(SCRIPT), "--spec", str(spec_file),
                                "--out", str(pathlib.Path(tmp) / "out.rs")],
                               capture_output=True, text=True)
            self.assertNotEqual(r.returncode, 0)
            self.assertIn("schema Bad: unsupported keyword oneOf", r.stderr)
            self.assertFalse((pathlib.Path(tmp) / "out.rs").exists())

    def test_other_unsupported_types_fail(self):
        for schema, why in [
            ({"type": ["string", "integer"]}, "unsupported type"),
            ({"type": "string", "format": "uuid"}, "unsupported format"),
            ({"type": "string", "enum": ["a"]}, "unsupported keyword enum"),
            ({"type": "object", "additionalProperties": True}, "unsupported keyword additionalProperties"),
        ]:
            with self.assertRaisesRegex(gen.GenError, f"schema Thing.v: {why}"):
                render(document({"Thing": obj({"v": prop(schema)})}))

    def test_a_property_without_a_description_fails_inline_ones_included(self):
        doc = document({"Thing": obj({"v": {"type": "string"}})})
        with self.assertRaisesRegex(gen.GenError, r"schema Thing\.v: no description"):
            render(doc)
        doc = document({"ApiError": obj({"error": prop({
            "type": "object", "required": ["message"],
            "properties": {"message": {"type": "string"}}}, "The error.")})})
        with self.assertRaisesRegex(gen.GenError, r"schema ApiError\.error\.message: no description"):
            render(doc)


class ParameterTest(unittest.TestCase):
    RANGE5 = {"type": "string", "enum": ["1h", "6h", "24h", "7d", "30d"], "default": "24h"}
    RANGE4 = {"type": "string", "enum": ["1h", "6h", "24h", "7d"], "default": "7d"}

    def doc(self, parameters, paths):
        return document(THING, parameters, paths)

    def test_parameters_with_the_same_values_share_one_enum(self):
        doc = self.doc({
            "UsageRange": query_param("range", self.RANGE5),
            "SessionsRange": query_param("range", dict(self.RANGE4, default="24h")),
            "WeekRange": query_param("range", self.RANGE4),
            "Flagged": query_param("flagged", {"type": "string", "enum": ["1"]}),
        }, {"/a": op("getA", ["UsageRange"]), "/b": op("listB", ["SessionsRange", "Flagged"]),
            "/c": op("getC", ["WeekRange"])})
        src = render(doc)
        self.assertEqual(src.count("pub enum "), 2)
        self.assertLess(src.index("pub enum UsageRange {"), src.index("pub enum Range {"))
        self.assertIn("    /// `30d`\n    D30,\n", src)
        self.assertIn('Self::H24 => "24h",', src)
        self.assertIn("/// A time window ending now.\n", src)
        self.assertIn("pub fn range(mut self, v: UsageRange) -> Self {", src)
        self.assertEqual(src.count("pub fn range(mut self, v: Range) -> Self {"), 2)
        self.assertIn("pub fn flagged(mut self, v: bool) -> Self {", src)
        self.assertIn('if self.flagged {\n            pairs.push(("flagged", "1".to_owned()));', src)

    def test_another_enum_fails_naming_the_parameter(self):
        doc = self.doc({"Mode": query_param("mode", {"type": "string", "enum": ["a", "b"]})},
                       {"/a": op("getA", ["Mode"])})
        with self.assertRaisesRegex(gen.GenError, r"parameter Mode: unsupported enum \['a', 'b'\]"):
            render(doc)

    def test_setter_types_and_query_pairs(self):
        doc = self.doc({
            "User": query_param("user", {"type": "string"}, "Only this user."),
            "After": query_param("after", {"type": "string", "format": "date-time"}),
            "Version": query_param("version", {"type": "integer", "minimum": 1}),
        }, {"/a": op("listA", ["User", "After", "Version"])})
        src = render(doc)
        self.assertIn("    /// Only this user.\n    pub fn user(mut self, v: impl Into<String>) -> Self {", src)
        self.assertIn("pub fn after(mut self, v: chrono::DateTime<chrono::Utc>) -> Self {", src)
        self.assertIn("v.to_rfc3339_opts(chrono::SecondsFormat::AutoSi, true)", src)
        self.assertIn("pub fn version(mut self, v: u64) -> Self {", src)
        self.assertIn('pairs.push(("version", v.to_string()));', src)
        self.assertIn("#[derive(Debug, Clone, PartialEq, Default)]\n#[non_exhaustive]\n"
                      "pub struct ListAQuery {", src)

    def test_names_path_parameters_and_segments(self):
        doc = self.doc({
            "PromptName": {"name": "name", "in": "path", "required": True,
                           "description": "The prompt name.", "schema": {"type": "string"}},
            "WeekRange": query_param("range", self.RANGE4),
        }, {"/api/v1/prompts/{name}/versions": op("getPromptVersions", ["PromptName", "WeekRange"]),
            "/api/v1/openapi.json": op("getOpenApi", [], None)})
        src = render(doc)
        self.assertIn("#[derive(Debug, Clone, PartialEq)]\n#[non_exhaustive]\n"
                      "pub struct GetPromptVersionsQuery {", src)
        self.assertIn("pub fn new(name: impl Into<String>) -> Self {", src)
        self.assertIn("/// `name`: The prompt name.", src)
        self.assertIn("pub async fn get_prompt_versions(&self, query: &GetPromptVersionsQuery)"
                      " -> Result<Thing, Error> {", src)
        self.assertIn('self.get_json(&[Seg::Lit("api"), Seg::Lit("v1"), Seg::Lit("prompts"), '
                      'Seg::Param(&query.name), Seg::Lit("versions")], query.query_pairs()).await',
                      src)
        self.assertIn("pub struct GetOpenApiQuery {", src)
        self.assertIn("pub async fn get_open_api(&self, query: &GetOpenApiQuery)"
                      " -> Result<serde_json::Value, Error> {", src)
        self.assertIn("    /// Some things.\n    ///\n    /// All of them.\n", src)

    def test_the_naming_helpers(self):
        self.assertEqual(gen.pascal("getUsageBreakdown"), "GetUsageBreakdown")
        self.assertEqual(gen.pascal("error"), "Error")
        self.assertEqual(gen.pascal("after_id"), "AfterId")
        self.assertEqual(gen.snake("getOpenApi"), "get_open_api")
        self.assertEqual(gen.snake("listPendingReviews"), "list_pending_reviews")
        self.assertEqual(gen.ident("type", "x"), "r#type")
        self.assertEqual(gen.variant("30d", "x"), "D30")


