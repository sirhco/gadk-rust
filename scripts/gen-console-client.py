"""Generates `crates/gadk-console-client/src/generated.rs` from the console's OpenAPI document.

Reads only `components.schemas`, `components.parameters` and each path's `get`. A schema or
parameter that uses anything outside the supported set, or a schema property without a
`description`, stops the generator with an error naming it. The output goes through
`rustfmt --edition 2024`.

Usage: gen-console-client.py [--check] [--spec FILE] [--out FILE]
Exit 0: written (with --check: up to date); 1: --check found a stale file; 2: error.
"""
import argparse, json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = "crates/gadk-console/src/web/api/openapi.json"
OUT = "crates/gadk-console-client/src/generated.rs"
HEADER = (
    f"// @generated by scripts/gen-console-client.py from {SPEC}.\n"
    "// Do not edit: run `python3 scripts/gen-console-client.py` to regenerate.\n"
)

# The schema keywords the generator understands; any other keyword is an error.
SCHEMA_KEYS = {"type", "properties", "required", "items", "$ref", "allOf", "prefixItems",
               "minItems", "format", "minimum", "default", "description"}
PARAM_KEYS = {"name", "in", "required", "description", "schema"}
PARAM_SCHEMA_KEYS = {"type", "enum", "format", "minimum", "default"}
# Range enums by their wire values; any other enum is an error, except FLAG.
RANGE_ENUMS = {("1h", "6h", "24h", "7d", "30d"): "UsageRange", ("1h", "6h", "24h", "7d"): "Range"}
FLAG = ("1",)
RANGE_DOC = "A time window ending now."
STRUCT_DERIVE = "#[derive(Debug, Clone, PartialEq, serde::Deserialize, serde::Serialize)]"
KEYWORDS = {"as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern",
            "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
            "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use",
            "where", "while", "abstract", "become", "box", "do", "final", "gen", "macro",
            "override", "priv", "try", "typeof", "unsized", "virtual", "yield"}


class GenError(Exception):
    """A document the generator does not support."""


def load(path):
    """The JSON document at `path`."""
    return json.loads(pathlib.Path(path).read_text(encoding="utf-8"))


def pascal(name):
    """`getUsageBreakdown` -> `GetUsageBreakdown`, `after_id` -> `AfterId`."""
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[_\-]", name) if p)


def snake(name):
    """`getOpenApi` -> `get_open_api`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def ident(name, where):
    """`name` as a Rust field or parameter name (`r#type` for a keyword)."""
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", name) or name in {"self", "super", "crate"}:
        raise GenError(f"{where}: unsupported name {name!r}")
    return f"r#{name}" if name in KEYWORDS else name


def variant(value, where):
    """The enum variant of a range value: `24h` -> `H24`, `30d` -> `D30`."""
    m = re.fullmatch(r"(\d+)([a-z])", value)
    if not m:
        raise GenError(f"{where}: unsupported enum value {value!r}")
    return m.group(2).upper() + m.group(1)


def doc(text, indent=""):
    """`text` as `///` lines."""
    return "".join(f"{indent}/// {line}".rstrip() + "\n" for line in text.split("\n"))


def sentence(text):
    """`text` ending with a full stop."""
    return text if text.endswith((".", "!", "?")) else text + "."


def need(node, key, where):
    """`node[key]`, or an error naming `where`."""
    if not isinstance(node, dict) or key not in node:
        raise GenError(f"{where}: missing {key}")
    return node[key]


def description(node, where):
    """The `description` of `node`: a property or schema without one is an error."""
    text = node.get("description") if isinstance(node, dict) else None
    if not isinstance(text, str) or not text.strip():
        raise GenError(f"{where}: no description")
    return text


def check_keys(schema, allowed, where):
    """An error naming the first keyword of `schema` outside `allowed`."""
    if not isinstance(schema, dict):
        raise GenError(f"{where}: not a schema object")
    extra = sorted(set(schema) - allowed)
    if extra:
        raise GenError(f"{where}: unsupported keyword {extra[0]}")


def type_of(schema, where):
    """(`type`, nullable): one type, or one type plus `"null"`."""
    t = schema.get("type")
    if isinstance(t, str) and t != "null":
        return t, False
    if isinstance(t, list) and len(t) == 2 and t[1] == "null" and isinstance(t[0], str) and t[0] != "null":
        return t[0], True
    raise GenError(f"{where}: unsupported type {t!r}")


class Gen:
    """The Rust source of one document: range enums, schema types, query structs and methods."""

    def __init__(self, doc):
        self.doc = doc
        self.schemas = need(need(doc, "components", "document"), "schemas", "components")
        self.parameters = need(doc["components"], "parameters", "components")
        self.items = []  # Rust items (structs), in emission order
        self.enums = {}  # wire values -> enum name, in first-use order

    def resolve(self, ref, kind, where):
        """The `#/components/<kind>/<name>` target of `ref` and its name."""
        prefix = f"#/components/{kind}/"
        if not isinstance(ref, str) or not ref.startswith(prefix):
            raise GenError(f"{where}: unsupported $ref {ref!r}")
        name = ref[len(prefix):]
        target = self.doc["components"][kind].get(name)
        if target is None:
            raise GenError(f"{where}: unknown $ref {ref}")
        return target, name

    # ---- schemas ---------------------------------------------------------------------------

    def rust_type(self, schema, where, inline_name):
        """(Rust type, nullable) of a property or item schema; an inline object becomes the
        struct `inline_name`."""
        check_keys(schema, SCHEMA_KEYS, where)
        if "$ref" in schema:
            if set(schema) - {"$ref", "description"}:
                raise GenError(f"{where}: $ref with other keywords")
            _, name = self.resolve(schema["$ref"], "schemas", where)
            return name, False
        for key in ("allOf", "prefixItems"):
            if key in schema:
                raise GenError(f"{where}: {key} is supported on a top-level schema only")
        t, nullable = type_of(schema, where)
        fmt = schema.get("format")
        if fmt is not None and (t, fmt) != ("string", "date-time"):
            raise GenError(f"{where}: unsupported format {fmt!r}")
        if t == "string":
            rt = "chrono::DateTime<chrono::Utc>" if fmt == "date-time" else "String"
        elif t == "integer":
            minimum = schema.get("minimum")
            rt = "u64" if isinstance(minimum, (int, float)) and minimum >= 0 else "i64"
        elif t == "number":
            rt = "f64"
        elif t == "boolean":
            rt = "bool"
        elif t == "array":
            items = schema.get("items")
            if not isinstance(items, dict):
                raise GenError(f"{where}: an array needs an items schema")
            inner, inner_null = self.rust_type(items, f"{where}.items", inline_name)
            rt = f"Vec<Option<{inner}>>" if inner_null else f"Vec<{inner}>"
        elif t == "object":
            self.emit_object(inline_name, schema, description(schema, where), where)
            rt = inline_name
        else:
            raise GenError(f"{where}: unsupported type {t!r}")
        return rt, nullable

    def emit_object(self, name, schema, text, where):
        """`pub struct name` with one field per property, in order."""
        props = schema.get("properties", {})
        required = schema.get("required", [])
        for r in required:
            if r not in props:
                raise GenError(f"{where}: required {r!r} is not a property")
        fields = []
        for pname, prop in props.items():
            pwhere = f"{where}.{pname}"
            ptext = description(prop, pwhere)
            rt, nullable = self.rust_type(prop, pwhere, name + pascal(pname))
            if nullable or pname not in required:
                rt = f"Option<{rt}>"
            fields.append(doc(ptext, "    ") + f"    pub {ident(pname, pwhere)}: {rt},\n")
        self.items.append(
            doc(text) + STRUCT_DERIVE + "\n#[non_exhaustive]\n"
            + f"pub struct {name} {{\n" + "".join(fields) + "}\n"
        )

    def emit_struct(self, name, schema):
        """The Rust type of the top-level schema `name`: an object, an `allOf` of object
        `$ref`s (flattened) or a `prefixItems` tuple."""
        where = f"schema {name}"
        check_keys(schema, SCHEMA_KEYS, where)
        text = description(schema, where)
        if "allOf" in schema:
            if set(schema) - {"allOf", "description"}:
                raise GenError(f"{where}: allOf with other keywords")
            props, required = {}, []
            for member in schema["allOf"]:
                if not isinstance(member, dict) or set(member) != {"$ref"}:
                    raise GenError(f"{where}: an allOf member must be a $ref")
                target, mname = self.resolve(member["$ref"], "schemas", where)
                if target.get("type") != "object" or "allOf" in target:
                    raise GenError(f"{where}: allOf member {mname} is not an object schema")
                for pname, prop in target.get("properties", {}).items():
                    if pname in props:
                        raise GenError(f"{where}: property {pname} appears twice")
                    props[pname] = prop
                required += target.get("required", [])
            self.emit_object(name, {"properties": props, "required": required}, text, where)
            return
        t, nullable = type_of(schema, where)
        if nullable:
            raise GenError(f"{where}: a top-level schema cannot be nullable")
        if "prefixItems" in schema:
            prefix = schema["prefixItems"]
            if t != "array" or schema.get("items") is not False or not isinstance(prefix, list) \
                    or schema.get("minItems") != len(prefix):
                raise GenError(f"{where}: prefixItems needs type array, items false and minItems")
            fields = []
            for i, item in enumerate(prefix):
                rt, item_null = self.rust_type(item, f"{where}.prefixItems[{i}]", f"{name}{i}")
                rt = f"Option<{rt}>" if item_null else rt
                own = item.get("description") if isinstance(item, dict) else None
                etext = own if isinstance(own, str) and own.strip() else f"Element {i}."
                fields.append(doc(etext, "    ") + f"    pub {rt},\n")
            self.items.append(
                doc(text) + STRUCT_DERIVE + "\n#[non_exhaustive]\n"
                + f"pub struct {name}(\n" + "".join(fields) + ");\n"
            )
            return
        if t != "object":
            raise GenError(f"{where}: a top-level schema must be an object, an allOf or a tuple")
        self.emit_object(name, schema, text, where)

    # ---- parameters ------------------------------------------------------------------------

    def param(self, name, p):
        """The parameter `name` (a `components.parameters` key) as a dict: `name`, `in`,
        `description`, `rust` (setter type), `kind` (`enum`, `flag`, `string`, `date-time`,
        `integer`)."""
        where = f"parameter {name}"
        check_keys(p, PARAM_KEYS, where)
        s = need(p, "schema", where)
        check_keys(s, PARAM_SCHEMA_KEYS, where)
        loc = need(p, "in", where)
        if loc not in ("query", "path"):
            raise GenError(f"{where}: unsupported in {loc!r}")
        t = s.get("type")
        fmt = s.get("format")
        if fmt is not None and (t, fmt) != ("string", "date-time"):
            raise GenError(f"{where}: unsupported format {fmt!r}")
        out = {"name": need(p, "name", where), "in": loc, "description": description(p, where)}
        ident(out["name"], where)
        if "enum" in s:
            values = tuple(s["enum"])
            if t != "string" or not all(isinstance(v, str) for v in values):
                raise GenError(f"{where}: an enum must be of strings")
            if values == FLAG:
                out.update(kind="flag", rust="bool")
            elif values in RANGE_ENUMS:
                for v in values:
                    variant(v, where)
                self.enums.setdefault(values, RANGE_ENUMS[values])
                out.update(kind="enum", rust=RANGE_ENUMS[values])
            else:
                raise GenError(f"{where}: unsupported enum {list(values)}")
        elif t == "string":
            if fmt == "date-time":
                out.update(kind="date-time", rust="chrono::DateTime<chrono::Utc>")
            else:
                out.update(kind="string", rust="String")
        elif t == "integer":
            minimum = s.get("minimum")
            unsigned = isinstance(minimum, (int, float)) and minimum >= 0
            out.update(kind="integer", rust="u64" if unsigned else "i64")
        else:
            raise GenError(f"{where}: unsupported type {t!r}")
        if loc == "path" and (out["kind"] != "string" or p.get("required") is not True):
            raise GenError(f"{where}: a path parameter must be a required string")
        return out

    def emit_enums(self):
        """One `#[non_exhaustive]` enum per distinct range tuple, in first-use order."""
        out = []
        for values, name in self.enums.items():
            variants = [(variant(v, name), v) for v in values]
            out.append(
                doc(RANGE_DOC) + "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n"
                + f"#[non_exhaustive]\npub enum {name} {{\n"
                + "".join(doc(f"`{v}`", "    ") + f"    {var},\n" for var, v in variants)
                + "}\n\n"
                + f"impl {name} {{\n"
                + "    /// The wire value, such as `24h`.\n"
                + "    pub fn as_str(&self) -> &'static str {\n        match self {\n"
                + "".join(f'            Self::{var} => "{v}",\n' for var, v in variants)
                + "        }\n    }\n}\n\n"
                + f"impl std::fmt::Display for {name} {{\n"
                + "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n"
                + "        f.write_str(self.as_str())\n    }\n}\n"
            )
        return out

    # ---- operations ------------------------------------------------------------------------

    def emit_operation(self, path, op, params):
        """The query struct of `GET path` and its `impl Client` method."""
        where = f"operation {path}"
        op_id = need(op, "operationId", where)
        if not isinstance(op_id, str) or not re.fullmatch(r"[a-z][A-Za-z0-9]*", op_id):
            raise GenError(f"{where}: unsupported operationId {op_id!r}")
        summary = sentence(need(op, "summary", where))
        mine = []
        for p in op.get("parameters", []):
            _, pname = self.resolve(need(p, "$ref", where), "parameters", where)
            mine.append(params[pname])
        names = re.findall(r"\{([^}]*)\}", path)
        path_params = []
        for n in names:
            match = [p for p in mine if p["in"] == "path" and p["name"] == n]
            if len(match) != 1:
                raise GenError(f"{where}: path parameter {n!r} is not declared once")
            path_params.append(match[0])
        if len([p for p in mine if p["in"] == "path"]) != len(names):
            raise GenError(f"{where}: a path parameter is not in the path")
        query_params = [p for p in mine if p["in"] == "query"]
        schema = need(need(need(need(need(op, "responses", where), "200", where), "content", where),
                           "application/json", where), "schema", where)
        if schema == {"type": "object"}:
            ret = "serde_json::Value"
        elif isinstance(schema, dict) and set(schema) == {"$ref"}:
            _, ret = self.resolve(schema["$ref"], "schemas", where)
        else:
            raise GenError(f"{where}: the 200 schema must be a $ref or {{\"type\": \"object\"}}")

        struct = pascal(op_id) + "Query"
        method = snake(op_id)
        fields = [f"    {ident(p['name'], where)}: String,\n" for p in path_params]
        for p in query_params:
            rust = "bool" if p["kind"] == "flag" else f"Option<{p['rust']}>"
            fields.append(f"    {ident(p['name'], where)}: {rust},\n")
        derive = "Debug, Clone, PartialEq" + ("" if path_params else ", Default")
        new_doc = "The query with the server's defaults."
        if path_params:
            new_doc += ("\n\nEach path parameter is sent percent-encoded as one path segment;"
                        " pass it unencoded.\n")
            new_doc += "\n".join(f"\n`{p['name']}`: {p['description']}" for p in path_params)
        args = ", ".join(f"{ident(p['name'], where)}: impl Into<String>" for p in path_params)
        if path_params:
            inits = "".join(f"            {ident(p['name'], where)}: {ident(p['name'], where)}.into(),\n"
                            for p in path_params)
            inits += "".join(
                f"            {ident(p['name'], where)}: {'false' if p['kind'] == 'flag' else 'None'},\n"
                for p in query_params)
            new_body = f"        Self {{\n{inits}        }}\n"
        else:
            new_body = "        Self::default()\n"
        setters, pairs = [], []
        for p in query_params:
            f = ident(p["name"], where)
            if p["kind"] == "flag":
                setters.append(doc(p["description"], "    ")
                               + f"    pub fn {f}(mut self, v: bool) -> Self {{\n"
                               + f"        self.{f} = v;\n        self\n    }}\n")
                pairs.append(f'        if self.{f} {{\n            pairs.push(("{p["name"]}", "1".to_owned()));\n        }}\n')
                continue
            if p["kind"] == "string":
                arg, store = "impl Into<String>", "v.into()"
            else:
                arg, store = p["rust"], "v"
            setters.append(doc(p["description"], "    ")
                           + f"    pub fn {f}(mut self, v: {arg}) -> Self {{\n"
                           + f"        self.{f} = Some({store});\n        self\n    }}\n")
            value = {
                "enum": "v.as_str().to_owned()",
                "string": "v.clone()",
                "date-time": "v.to_rfc3339_opts(chrono::SecondsFormat::AutoSi, true)",
                "integer": "v.to_string()",
            }[p["kind"]]
            pairs.append(f'        if let Some(v) = &self.{f} {{\n            pairs.push(("{p["name"]}", {value}));\n        }}\n')
        if pairs:
            pairs_body = ("        let mut pairs: Vec<(&'static str, String)> = Vec::new();\n"
                          + "".join(pairs) + "        pairs\n")
        else:
            pairs_body = "        Vec::new()\n"
        self.items.append(
            doc(summary) + f"#[derive({derive})]\n#[non_exhaustive]\n"
            + f"pub struct {struct} {{\n" + "".join(fields) + "}\n\n"
            + f"impl {struct} {{\n"
            + doc(new_doc, "    ") + f"    pub fn new({args}) -> Self {{\n" + new_body + "    }\n\n"
            + "".join(s + "\n" for s in setters)
            + "    /// The query pairs to send: the parameters that are set.\n"
            + "    fn query_pairs(&self) -> Vec<(&'static str, String)> {\n" + pairs_body + "    }\n"
            + "}\n"
        )
        segments = []
        for seg in path.strip("/").split("/"):
            m = re.fullmatch(r"\{(.+)\}", seg)
            segments.append(f"Seg::Param(&query.{ident(m.group(1), where)})" if m
                            else f'Seg::Lit("{seg}")')
        method_doc = summary
        if op.get("description"):
            method_doc += "\n\n" + op["description"]
        method_doc += (f"\n\n`GET {path}`\n\n# Errors\n\n"
                       "[`Error`] when the request fails, the console answers a non-2xx status or"
                       " the body does not decode.")
        return (doc(method_doc, "    ")
                + f"    pub async fn {method}(&self, query: &{struct}) -> Result<{ret}, Error> {{\n"
                + f"        self.get_json(&[{', '.join(segments)}], query.query_pairs()).await\n"
                + "    }\n")

    # ---- the file --------------------------------------------------------------------------

    def render(self):
        """The unformatted Rust source."""
        params = {name: self.param(name, p) for name, p in self.parameters.items()}
        enums = self.emit_enums()
        for name, schema in self.schemas.items():
            self.emit_struct(name, schema)
        methods = []
        for path, item in need(self.doc, "paths", "document").items():
            methods.append(self.emit_operation(path, need(item, "get", f"path {path}"), params))
        return (
            HEADER + "\n"
            + "//! The types and operations of the console's JSON API, generated from its OpenAPI"
            + " document.\n\n"
            + "use crate::client::{Client, Seg};\nuse crate::error::Error;\n\n"
            + "\n".join(enums + self.items) + "\n"
            + "impl Client {\n" + "\n".join(methods) + "}\n"
        )


def rustfmt(src):
    """`src` formatted by the workspace toolchain's `rustfmt --edition 2024`."""
    try:
        r = subprocess.run(["rustfmt", "--edition", "2024"], input=src, capture_output=True,
                           text=True, cwd=ROOT, check=False)
    except OSError as e:
        raise GenError(f"rustfmt: {e}") from e
    if r.returncode != 0:
        raise GenError(f"rustfmt failed: {r.stderr.strip()}")
    return r.stdout


def generate(doc):
    """The formatted `generated.rs` of the document `doc`."""
    return rustfmt(Gen(doc).render())


def shown(path):
    """`path` relative to the repository when it is inside it."""
    try:
        return str(pathlib.Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the output file differs from a fresh generation")
    ap.add_argument("--spec", default=str(ROOT / SPEC), help="the OpenAPI document")
    ap.add_argument("--out", default=str(ROOT / OUT), help="the generated Rust file")
    args = ap.parse_args(argv)
    out = pathlib.Path(args.out)
    try:
        text = generate(load(args.spec))
        if args.check:
            current = out.read_text(encoding="utf-8") if out.exists() else None
            if current != text:
                print(f"{shown(out)} is stale: run python3 scripts/gen-console-client.py",
                      file=sys.stderr)
                return 1
            return 0
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        return 0
    except Exception as e:  # any failure is exit 2, never 1 (which means stale)
        print(f"gen-console-client: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
