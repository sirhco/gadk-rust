//! Generates `crates/gadk-agentanalytics/src/storagepb/*.rs` from the vendored protos.
//!
//! Usage: `gen-storagepb <PROTO_DIR> <OUT_DIR>` (run through `run.sh`).
//!
//! prost messages are written per package (`google.cloud.bigquery.storage.v1.rs`,
//! `google.protobuf.rs`, `google.rpc.rs`) with `compile_well_known_types`, so the output needs
//! no `prost-types`. The `google.api` files are imported only for options (annotations, which
//! prost does not model) and are dropped from the descriptor set before generation. The tonic
//! client goes into the package file; the tonic server goes into its own
//! `google.cloud.bigquery.storage.v1.server.rs`, so the hand-written `storagepb/mod.rs` can gate
//! it behind `cfg(any(test, feature = "testutil"))` while including every file unmodified.

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::rc::Rc;
use std::{env, fs, io};

/// googleapis commit the `google/api`, `google/rpc` and `google/cloud` protos come from.
const GOOGLEAPIS_COMMIT: &str = "3614450147d75067801a8da2ae59abb55b82cc30";
/// protocolbuffers/protobuf commit (tag v36.2) the `google/protobuf` protos come from.
const PROTOBUF_COMMIT: &str = "2c74169b34066ceb8ddb6b882fcb3fb32d737a55";
const GENERATOR: &str = "scripts/gen-storagepb (tonic-prost-build 0.14.9, prost-build 0.14.5, \
                         protoc 36.2 from protoc-bin-vendored 3.3.0)";

const PROTOS: &[&str] = &[
    "google/cloud/bigquery/storage/v1/storage.proto",
    "google/cloud/bigquery/storage/v1/stream.proto",
    "google/cloud/bigquery/storage/v1/arrow.proto",
    "google/cloud/bigquery/storage/v1/avro.proto",
    "google/cloud/bigquery/storage/v1/protobuf.proto",
    "google/cloud/bigquery/storage/v1/table.proto",
];

/// Server code per proto package, collected while prost generates the package files.
type ServerCode = Rc<RefCell<BTreeMap<String, String>>>;

/// Sends each service's client to prost's package buffer and its server to [`ServerCode`].
struct SplitServiceGenerator {
    client: Box<dyn prost_build::ServiceGenerator>,
    server: Box<dyn prost_build::ServiceGenerator>,
    server_code: ServerCode,
}

impl prost_build::ServiceGenerator for SplitServiceGenerator {
    fn generate(&mut self, service: prost_build::Service, buf: &mut String) {
        let package = service.package.clone();
        self.client.generate(service.clone(), buf);
        let mut server_code = self.server_code.borrow_mut();
        let server_buf = server_code.entry(package).or_default();
        self.server.generate(service, server_buf);
    }
}

fn header() -> String {
    format!(
        "// @generated by {GENERATOR}\n\
         // from googleapis {GOOGLEAPIS_COMMIT} and protocolbuffers/protobuf {PROTOBUF_COMMIT}\n\
         // (crates/gadk-agentanalytics/proto). Do not edit: regenerate with scripts/gen-storagepb/run.sh.\n"
    )
}

fn tonic_builder() -> tonic_prost_build::Builder {
    tonic_prost_build::configure()
        .build_transport(false)
        .compile_well_known_types(true)
}

fn generate(proto_dir: &Path, out_dir: &Path) -> io::Result<()> {
    let server_code: ServerCode = Rc::default();
    let mut config = prost_build::Config::new();
    config
        .protoc_executable(protoc_bin_vendored::protoc_bin_path().map_err(io::Error::other)?)
        .out_dir(out_dir)
        .compile_well_known_types()
        .service_generator(Box::new(SplitServiceGenerator {
            client: tonic_builder()
                .build_client(true)
                .build_server(false)
                .service_generator(),
            server: tonic_builder()
                .build_client(false)
                .build_server(true)
                .service_generator(),
            server_code: Rc::clone(&server_code),
        }));
    let protos: Vec<PathBuf> = PROTOS.iter().map(|p| proto_dir.join(p)).collect();
    let mut fds = config.load_fds(&protos, &[proto_dir])?;
    fds.file.retain(|file| file.package() != "google.api");
    config.compile_fds(fds)?;

    for (package, code) in server_code.borrow().iter() {
        fs::write(out_dir.join(format!("{package}.server.rs")), code)?;
    }
    // Prefix every generated file with the provenance header.
    let mut names: Vec<PathBuf> = fs::read_dir(out_dir)?
        .map(|entry| entry.map(|e| e.path()))
        .collect::<io::Result<_>>()?;
    names.retain(|p| {
        p.file_name()
            .and_then(|n| n.to_str())
            .is_some_and(|n| n.starts_with("google.") && n.ends_with(".rs"))
    });
    names.sort();
    for path in names {
        let body = fs::read_to_string(&path)?;
        fs::write(&path, format!("{}{body}", header()))?;
    }
    Ok(())
}

fn main() -> io::Result<()> {
    let args: Vec<String> = env::args().collect();
    let [_, proto_dir, out_dir] = args.as_slice() else {
        return Err(io::Error::other(
            "usage: gen-storagepb <PROTO_DIR> <OUT_DIR>",
        ));
    };
    let out_dir = Path::new(out_dir);
    fs::create_dir_all(out_dir)?;
    generate(Path::new(proto_dir), out_dir)
}
