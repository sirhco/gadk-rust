//! File and image types.

use crate::serde_util::{base64_bytes, i64_string_opt, is_zero};
use bytes::Bytes;
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use std::collections::BTreeMap;

crate::string_enum!(
    /// Enum that controls the generation of people.
    PersonGeneration {
        /// Do not generate images of people.
        DontAllow => "DONT_ALLOW",
        /// Generate images of adults only.
        AllowAdult => "ALLOW_ADULT",
        /// Generate images of adults and children.
        AllowAll => "ALLOW_ALL",
    }
);

crate::string_enum!(
    /// Enum that controls the safety filter level for objectionable content.
    SafetyFilterLevel {
        /// Block content with a low or higher probability of being unsafe (strictest).
        BlockLowAndAbove => "BLOCK_LOW_AND_ABOVE",
        /// Block content with a medium or higher probability of being unsafe.
        BlockMediumAndAbove => "BLOCK_MEDIUM_AND_ABOVE",
        /// Block only content with a high probability of being unsafe.
        BlockOnlyHigh => "BLOCK_ONLY_HIGH",
        /// Block nothing.
        BlockNone => "BLOCK_NONE",
    }
);

crate::string_enum!(
    /// Enum that specifies the language of the text in the prompt.
    ImagePromptLanguage {
        /// Detect the prompt language automatically.
        Auto => "auto",
        /// English.
        En => "en",
        /// Japanese.
        Ja => "ja",
        /// Korean.
        Ko => "ko",
        /// Hindi.
        Hi => "hi",
        /// Chinese.
        Zh => "zh",
        /// Portuguese.
        Pt => "pt",
        /// Spanish.
        Es => "es",
    }
);

crate::string_enum!(
    /// State for the lifecycle of a File.
    FileState {
        /// Not specified.
        Unspecified => "STATE_UNSPECIFIED",
        /// The file is still being processed and cannot be used yet.
        Processing => "PROCESSING",
        /// The file is processed and ready to use.
        Active => "ACTIVE",
        /// Processing the file failed; see [`File::error`].
        Failed => "FAILED",
    }
);

crate::string_enum!(
    /// Source of the File.
    FileSource {
        /// Not specified.
        Unspecified => "SOURCE_UNSPECIFIED",
        /// Uploaded by the user.
        Uploaded => "UPLOADED",
        /// Generated by the API.
        Generated => "GENERATED",
        /// Registered from an existing storage location.
        Registered => "REGISTERED",
    }
);

/// The configuration for generating images. You
/// can find API default values and more details at Gemini Enterprise Agent Platform:
/// <https://cloud.google.com/vertex-ai/generative-ai/docs/model-reference/imagen-api>.
/// GeminiAPI: <https://ai.google.dev/gemini-api/docs/imagen#imagen-model>
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerateImagesConfig {
    /// Cloud Storage URI prefix where generated images are written (Vertex AI only).
    #[serde(default, skip_serializing_if = "is_zero")]
    pub output_gcs_uri: String,
    /// What to avoid in the generated images.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub negative_prompt: String,
    /// How many images to generate.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub number_of_images: i32,
    /// Aspect ratio of the images, such as `"1:1"`, `"16:9"` or `"9:16"`.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub aspect_ratio: String,
    /// How closely the images follow the prompt; higher values follow it more strictly.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub guidance_scale: Option<f32>,
    /// Random seed, for reproducible output.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub seed: Option<i32>,
    /// How aggressively unsafe content is filtered.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub safety_filter_level: Option<SafetyFilterLevel>,
    /// Whether images of people may be generated.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub person_generation: Option<PersonGeneration>,
    /// Whether to return safety scores for each image and the prompt.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub include_safety_attributes: bool,
    /// Whether to return the reason an image was filtered by Responsible AI filtering.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub include_rai_reason: bool,
    /// Language of the prompt.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub language: Option<ImagePromptLanguage>,
    /// MIME type of the generated images, such as `"image/png"` or `"image/jpeg"`.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub output_mime_type: String,
    /// JPEG compression quality (0–100), when `output_mime_type` is `"image/jpeg"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_compression_quality: Option<i32>,
    /// Whether to add an invisible SynthID watermark to the images.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub add_watermark: bool,
    /// User-defined labels attached to the request (Vertex AI only), e.g. for billing breakdown.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub labels: BTreeMap<String, String>,
    /// Size of the generated images, such as `"1K"` or `"2K"`.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub image_size: String,
    /// Whether to let the model rewrite the prompt before generating.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub enhance_prompt: bool,
}

/// An image.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Image {
    /// Cloud Storage URI of the image.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub gcs_uri: String,
    /// The image bytes; base64 on the wire.
    #[serde(
        default,
        skip_serializing_if = "Bytes::is_empty",
        with = "base64_bytes"
    )]
    pub image_bytes: Bytes,
    /// IANA MIME type of the image.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub mime_type: String,
}

/// Safety attributes of a GeneratedImage or the user-provided prompt.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SafetyAttributes {
    /// Names of the safety categories.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub categories: Vec<String>,
    /// Scores for `categories`, in the same order.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub scores: Vec<f32>,
    /// What was rated: the image or the prompt.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub content_type: String,
}

/// An output image.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedImage {
    /// The generated image.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image: Option<Image>,
    /// Why the image was filtered by Responsible AI filtering, when it was.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub rai_filtered_reason: String,
    /// Safety scores of the image.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub safety_attributes: Option<SafetyAttributes>,
    /// The rewritten prompt used to generate the image, when prompt enhancement was on.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub enhanced_prompt: String,
}

/// The output images response.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerateImagesResponse {
    /// The generated images.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub generated_images: Vec<GeneratedImage>,
    /// Safety scores of the prompt.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub positive_prompt_safety_attributes: Option<SafetyAttributes>,
}

/// Status of a File that uses a common error model.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct FileStatus {
    /// Error details: a list of messages carrying error specifics.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub details: Vec<Map<String, Value>>,
    /// Developer-facing error message.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub message: String,
    /// Status code: a gRPC status code value.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub code: Option<i32>,
}

/// A file uploaded to the API.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct File {
    /// Resource name of the file, `files/{id}`.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub name: String,
    /// Human-readable display name.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub display_name: String,
    /// IANA MIME type of the file.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub mime_type: String,
    /// Size of the file in bytes; a quoted integer on the wire.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        with = "i64_string_opt"
    )]
    pub size_bytes: Option<i64>,
    /// When the file was created.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub create_time: Option<DateTime<Utc>>,
    /// When the file is deleted, for files with an expiration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expiration_time: Option<DateTime<Utc>>,
    /// When the file was last updated.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub update_time: Option<DateTime<Utc>>,
    /// SHA-256 hash of the uploaded bytes (base64-encoded).
    #[serde(default, skip_serializing_if = "is_zero")]
    pub sha256_hash: String,
    /// URI of the file, for referencing it in requests.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub uri: String,
    /// URI to download the file from.
    #[serde(default, skip_serializing_if = "is_zero")]
    pub download_uri: String,
    /// Processing state of the file.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub state: Option<FileState>,
    /// Where the file came from.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<FileSource>,
    /// Metadata of a video file.
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub video_metadata: Map<String, Value>,
    /// The error, when processing failed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<FileStatus>,
}
