#[tokio::test]
async fn test_database_service_append_event_preserves_input_event_temp_state() {
    let svc = memory_service().await;
    let created = create(&svc, "testapp", "testuser").await;
    let mut event = Event {
        id: "event1".into(),
        timestamp: Utc::now(),
        actions: EventActions {
            state_delta: state(json!({"temp:k1": "v1", "sk": "v2"})),
            ..Default::default()
        },
        ..Default::default()
    };
    svc.append_event(created.as_ref(), &mut event)
        .await
        .unwrap();

    // The input event's delta is not mutated.
    let delta = event.actions.state_delta.as_ref().unwrap();
    assert!(
        delta.contains_key("temp:k1"),
        "expected temp:k1 to be preserved on input event: {delta:?}"
    );
    assert_eq!(
        delta["sk"],
        json!("v2"),
        "expected non-temp key sk to remain in input event"
    );

    // The stored event in the session has temp keys stripped.
    let stored = created
        .events()
        .last()
        .cloned()
        .expect("expected stored event in session");
    let stored_delta = stored.actions.state_delta.unwrap();
    assert!(
        !stored_delta.contains_key("temp:k1"),
        "expected temp:k1 to be stripped: {stored_delta:?}"
    );
    assert_eq!(stored_delta["sk"], json!("v2"));
}

// parity: adapted: the events carry fixed IDs and the order is asserted exactly (Go's random IDs leave "not reversed" failing whenever ascending ID order is reverse insertion order)
#[tokio::test]
async fn test_events_sharing_a_timestamp_come_back_in_a_stable_order() {
    let svc = memory_service().await;
    let sess = create(&svc, "app", "user").await;
    let platform = Platform::default();

    // Six events on one instant, appended in a known order.
    let ts = Utc.with_ymd_and_hms(2026, 1, 1, 0, 0, 0).unwrap();
    let mut want = Vec::new();
    for i in 0..6 {
        let mut ev = Event::new(&platform, "inv1");
        // Ties are broken by ID; IDs ascending with insertion make the expected order exact.
        ev.id = format!("e{i}");
        ev.author = "author".into();
        ev.timestamp = ts;
        ev.response.content = Some(Content::from_text(format!("event {i}"), ROLE_USER));
        svc.append_event(sess.as_ref(), &mut ev).await.unwrap();
        want.push(ev.id.clone());
    }

    let read = || async {
        get(&svc, sess.as_ref())
            .await
            .events()
            .into_iter()
            .map(|e| e.id)
            .collect::<Vec<_>>()
    };
    let first = read().await;
    for _ in 0..5 {
        assert_eq!(
            read().await,
            first,
            "the order of tied events changed between reads"
        );
    }
    assert_eq!(
        first, want,
        "tied events did not come back in insertion order"
    );
}

// parity: adapted: a statement log (feature testutil) records what Go's gorm callbacks record; sqlite has no FOR UPDATE, but the log records the locked read Go requests
#[tokio::test]
async fn test_database_service_append_event_locks_shared_state_rows() {
    let cases: [(&str, Option<Value>, &[&str]); 5] = [
        (
            "no_delta",
            None,
            &["select app_states", "select user_states"],
        ),
        (
            "session_only",
            Some(json!({"s": 1})),
            &["select app_states", "select user_states"],
        ),
        (
            "app_only",
            Some(json!({"app:a": 1})),
            &[
                "insert app_states on conflict do nothing",
                "select app_states for update",
                "select user_states",
            ],
        ),
        (
            "user_only",
            Some(json!({"user:u": 2})),
            &[
                "select app_states",
                "insert user_states on conflict do nothing",
                "select user_states for update",
            ],
        ),
        (
            "app_and_user",
            Some(json!({"app:a": 1, "user:u": 2, "s": 3})),
            &[
                "insert app_states on conflict do nothing",
                "select app_states for update",
                "insert user_states on conflict do nothing",
                "select user_states for update",
            ],
        ),
    ];
    for (name, delta, want) in cases {
        let (svc, log) = memory_service().await.with_statement_log();
        let created = create(&svc, "app", "user").await;
        log.lock().clear();
        let mut event = Event {
            id: "e1".into(),
            author: "user".into(),
            timestamp: Utc::now(),
            actions: EventActions {
                state_delta: delta.clone().map(|d| d.as_object().unwrap().clone()),
                ..Default::default()
            },
            ..Default::default()
        };
        svc.append_event(created.as_ref(), &mut event)
            .await
            .unwrap();
        assert_eq!(*log.lock(), want, "{name}: AppendEvent state statements");

        let got = get(&svc, created.as_ref()).await;
        for (key, value) in delta
            .as_ref()
            .and_then(Value::as_object)
            .into_iter()
            .flatten()
        {
            assert_eq!(
                got.state().get(key).ok().as_ref(),
                Some(value),
                "{name}: state[{key:?}]"
            );
        }
    }
}

