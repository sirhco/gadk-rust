// parity: adapted: the timestamps render in UTC (Go formats them in the local zone; equal under TZ=UTC)
#[tokio::test]
async fn test_database_service_append_event_stale_error_formats_timestamps() {
    let t0 = Utc.with_ymd_and_hms(2026, 7, 17, 10, 0, 0).unwrap();
    let svc = memory_service()
        .await
        .with_platform(Platform::default().with_time(move || t0));
    let created = create(&svc, "app", "user").await;
    // A second, independent handle on the same session — still pinned at t0.
    let stale = get(&svc, created.as_ref()).await;
    // Advance the stored session past t0 by appending through the fresh handle.
    let t1 = Utc.with_ymd_and_hms(2026, 7, 17, 11, 0, 0).unwrap();
    let mut e1 = Event {
        id: "e1".into(),
        author: "agent".into(),
        timestamp: t1,
        ..Default::default()
    };
    svc.append_event(created.as_ref(), &mut e1).await.unwrap();
    // Appending through the stale handle (updatedAt == t0 < stored t1) must fail.
    let mut e2 = Event {
        id: "e2".into(),
        author: "agent".into(),
        timestamp: t1,
        ..Default::default()
    };
    let err = svc.append_event(stale.as_ref(), &mut e2).await.unwrap_err();
    assert!(matches!(err, SessionError::Backend(_)), "{err:?}");
    let msg = err.to_string();
    assert!(
        !msg.contains("1970"),
        "stale error still renders a 1970 timestamp: {msg:?}"
    );
    assert_eq!(
        msg,
        "stale session error: last update time from request (2026-07-17T10:00:00Z) is older than in database (2026-07-17T11:00:00Z)"
    );
}

#[tokio::test]
async fn test_database_service_state_update_time_is_set() {
    let fixed = Utc.with_ymd_and_hms(2026, 7, 19, 17, 33, 48).unwrap();
    let svc = memory_service()
        .await
        .with_platform(Platform::default().with_time(move || fixed));
    let created = svc
        .create(CreateRequest {
            app_name: "app".into(),
            user_id: "user".into(),
            state: state(json!({"app:config": "v1", "user:pref": "x"})),
            ..Default::default()
        })
        .await
        .unwrap();
    let pool = svc.sqlite_pool().unwrap();
    let times = || async {
        let app: String =
            sqlx::query_scalar("SELECT update_time FROM app_states WHERE app_name = 'app'")
                .fetch_one(pool)
                .await
                .unwrap();
        let user: String = sqlx::query_scalar(
            "SELECT update_time FROM user_states WHERE app_name = 'app' AND user_id = 'user'",
        )
        .fetch_one(pool)
        .await
        .unwrap();
        (app, user)
    };
    assert_eq!(
        times().await,
        (
            "2026-07-19 17:33:48+00:00".to_string(),
            "2026-07-19 17:33:48+00:00".to_string()
        ),
        "app_states/user_states update_time after Create"
    );
    let mut event = Event {
        id: "e1".into(),
        author: "user".into(),
        timestamp: fixed + Duration::minutes(1),
        actions: EventActions {
            state_delta: state(json!({"app:config2": "v2", "user:pref2": "y"})),
            ..Default::default()
        },
        ..Default::default()
    };
    svc.append_event(created.as_ref(), &mut event)
        .await
        .unwrap();
    assert_eq!(
        times().await,
        (
            "2026-07-19 17:34:48+00:00".to_string(),
            "2026-07-19 17:34:48+00:00".to_string()
        ),
        "app_states/user_states update_time after AppendEvent"
    );
}

