fn state(v: Value) -> Option<Map<String, Value>> {
    Some(v.as_object().unwrap().clone())
}

async fn create(svc: &DatabaseSessionService, app: &str, user: &str) -> Arc<dyn Session> {
    svc.create(CreateRequest {
        app_name: app.into(),
        user_id: user.into(),
        ..Default::default()
    })
    .await
    .unwrap()
}

async fn get(svc: &DatabaseSessionService, s: &dyn Session) -> Arc<dyn Session> {
    svc.get(GetRequest {
        app_name: s.app_name().into(),
        user_id: s.user_id().into(),
        session_id: s.id().into(),
        ..Default::default()
    })
    .await
    .unwrap()
}

async fn pinned_memory_pool() -> sqlx::SqlitePool {
    sqlx::sqlite::SqlitePoolOptions::new()
        .max_connections(1)
        .min_connections(1)
        .idle_timeout(None)
        .max_lifetime(None)
        .connect("sqlite::memory:")
        .await
        .unwrap()
}

