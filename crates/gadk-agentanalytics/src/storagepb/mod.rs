//! Generated protobuf messages and tonic stubs for the BigQuery Storage API
//! (`google.cloud.bigquery.storage.v1`),
//! with the `google.protobuf` and `google.rpc` types they use.
//!
//! This file is hand-written; the `google.*.rs` files beside it are generated by
//! `scripts/gen-storagepb/run.sh` from the googleapis protos vendored under
//! `crates/gadk-agentanalytics/proto` and are included unmodified, so regeneration reproduces
//! them byte for byte. The tonic clients are always built; the tonic servers (used by the
//! in-process fake BigQuery Write server) only under `cfg(any(test, feature = "testutil"))`.
//! The `v1` package is re-exported at this module's root.

// Generated code is not held to the workspace lints: prost/tonic output trips clippy style lints
// (`doc_lazy_continuation`, `large_enum_variant`) and googleapis comments contain bare URLs; the
// workspace's restriction lints are allowed too so a regeneration never needs an edit here.
// prost leaves fields without proto comments undocumented, so `missing_docs` is allowed as well.
#![allow(
    missing_docs,
    clippy::all,
    clippy::unwrap_used,
    clippy::expect_used,
    rustdoc::bare_urls
)]

/// The `google` protobuf package tree.
pub mod google {
    /// `google.protobuf` well-known types (generated with `compile_well_known_types`).
    pub mod protobuf {
        include!("google.protobuf.rs");
    }

    /// `google.rpc` (`Status`).
    pub mod rpc {
        include!("google.rpc.rs");
    }

    /// `google.cloud`.
    pub mod cloud {
        /// `google.cloud.bigquery`.
        pub mod bigquery {
            /// `google.cloud.bigquery.storage`.
            pub mod storage {
                /// `google.cloud.bigquery.storage.v1`: messages, `big_query_write_client`,
                /// `big_query_read_client` and (test / `testutil`) the matching servers.
                pub mod v1 {
                    include!("google.cloud.bigquery.storage.v1.rs");

                    #[cfg(any(test, feature = "testutil"))]
                    include!("google.cloud.bigquery.storage.v1.server.rs");
                }
            }
        }
    }
}

pub use self::google::cloud::bigquery::storage::v1::*;
