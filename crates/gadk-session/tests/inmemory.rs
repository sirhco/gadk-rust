#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn test_in_memory_service_create_concurrent_access() {
    const GOROUTINES: usize = 16;
    const ATTEMPTS: usize = 32;
    let s = Arc::new(InMemorySessionService::new());
    let start = Arc::new(tokio::sync::Barrier::new(GOROUTINES));
    let success = Arc::new(AtomicI32::new(0));
    let errors = Arc::new(AtomicI32::new(0));

    let mut handles = Vec::new();
    for _ in 0..GOROUTINES {
        let (s, start, success, errors) =
            (s.clone(), start.clone(), success.clone(), errors.clone());
        handles.push(tokio::spawn(async move {
            start.wait().await;
            for _ in 0..ATTEMPTS {
                let res = s
                    .create(CreateRequest {
                        app_name: "race-app".into(),
                        user_id: "race-user".into(),
                        session_id: Some("race-session".into()),
                        ..Default::default()
                    })
                    .await;
                match res {
                    Ok(_) => {
                        success.fetch_add(1, Ordering::SeqCst);
                    }
                    Err(e) if e.to_string().contains("already exists") => {
                        errors.fetch_add(1, Ordering::SeqCst);
                    }
                    Err(_) => {}
                }
            }
        }));
    }
    for h in handles {
        h.await.unwrap();
    }

    assert_eq!(
        success.load(Ordering::SeqCst),
        1,
        "expected 1 successful creation"
    );
    let expected_errors = i32::try_from(GOROUTINES * ATTEMPTS - 1).unwrap();
    assert_eq!(
        errors.load(Ordering::SeqCst),
        expected_errors,
        "expected {expected_errors} 'already exists' errors"
    );
}

#[tokio::test]
async fn test_in_memory_session_append_event_workflow_fields_round_trip() {
    let service = InMemorySessionService::new();
    let sess = create(&service, "app", "user").await;

    const WANT_SCOPE: &str = "adk-task-isolation-scope";
    let mut event = Event {
        id: "wf_event".into(),
        author: "agent".into(),
        isolation_scope: WANT_SCOPE.into(),
        node_info: Some(NodeInfo {
            path: "ask_name".into(),
            ..Default::default()
        }),
        requested_input: Some(RequestInput {
            interrupt_id: "ask_name".into(),
            message: "What's your name?".into(),
            ..Default::default()
        }),
        routes: vec!["route_a".into()],
        ..Default::default()
    };
    service
        .append_event(sess.as_ref(), &mut event)
        .await
        .unwrap();

    let got = get(&service, sess.as_ref()).await;
    let evs = got.events();
    assert_eq!(evs.len(), 1, "got {} events, want 1", evs.len());
    let ev = &evs[0];
    assert!(
        ev.node_info.as_ref().is_some_and(|n| n.path == "ask_name"),
        "NodeInfo not persisted: {:?}",
        ev.node_info
    );
    assert!(
        ev.requested_input
            .as_ref()
            .is_some_and(|r| r.interrupt_id == "ask_name"),
        "RequestedInput not persisted: {:?}",
        ev.requested_input
    );
    assert_eq!(
        ev.routes,
        vec!["route_a".to_string()],
        "Routes not persisted"
    );
    assert_eq!(ev.isolation_scope, WANT_SCOPE, "IsolationScope");
}

// Regression guard for ADK-Go #530: `State::all` must snapshot under the lock. In Rust
// `all()` returns an owned `Vec`, so the Go map-iteration race cannot occur; the test still
// checks the observable invariants (seed key always present, count never goes backwards).
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn test_in_memory_state_all_concurrent_set() {
    const WRITERS: usize = 8;
    const ITERATIONS: usize = 200;
    let svc = Arc::new(InMemorySessionService::new());
    let sess = svc
        .create(CreateRequest {
            app_name: "app".into(),
            user_id: "user".into(),
            state: delta(&[("k0", json!(0))]),
            ..Default::default()
        })
        .await
        .unwrap();

    let start = Arc::new(tokio::sync::Barrier::new(WRITERS + 1));
    let mut handles = Vec::new();
    for w in 0..WRITERS {
        let (svc, sess, start) = (svc.clone(), sess.clone(), start.clone());
        handles.push(tokio::spawn(async move {
            start.wait().await;
            for i in 0..ITERATIONS {
                let mut ev = Event {
                    timestamp: Utc::now(),
                    actions: EventActions {
                        state_delta: delta(&[(&format!("w{w}_k{i}"), json!(i))]),
                        ..Default::default()
                    },
                    ..Default::default()
                };
                svc.append_event(sess.as_ref(), &mut ev)
                    .await
                    .unwrap_or_else(|e| panic!("AppendEvent(w{w}, i{i}) failed: {e}"));
            }
        }));
    }

    {
        let (sess, start) = (sess.clone(), start.clone());
        handles.push(tokio::spawn(async move {
            start.wait().await;
            let mut prev_count = 0;
            for _ in 0..ITERATIONS {
                let mut count = 0;
                let mut saw_seed = false;
                for (k, _) in sess.state().all() {
                    count += 1;
                    if k == "k0" {
                        saw_seed = true;
                    }
                }
                assert!(saw_seed, "All() did not yield seed key \"k0\"");
                assert!(
                    count >= prev_count,
                    "All() yielded {count} keys, want at least {prev_count} (the previous snapshot's count)"
                );
                prev_count = count;
                tokio::task::yield_now().await;
            }
        }));
    }
    for h in handles {
        h.await.unwrap();
    }
}

#[tokio::test]
async fn test_in_memory_state_all_is_snapshot() {
    let svc = InMemorySessionService::new();
    let sess = svc
        .create(CreateRequest {
            app_name: "app".into(),
            user_id: "user".into(),
            state: Some(Map::new()),
            ..Default::default()
        })
        .await
        .unwrap();
    let st = sess.state();
    for i in 0..64 {
        st.set(&format!("seed_{i:03}"), json!(i)).unwrap();
    }

    let mut got = Vec::new();
    let mut leaked = Vec::new();
    let mut first = true;
    for (k, _) in st.all() {
        if k.starts_with("injected_") {
            leaked.push(k.clone());
        }
        got.push(k);
        if first {
            // mutate hard, once, while iteration is live
            first = false;
            for i in 0..2048 {
                let _ = st.set(&format!("injected_{i:05}"), json!(i));
            }
        }
    }

    assert!(
        leaked.is_empty(),
        "All() yielded {} keys written after iteration began, e.g. {:?}",
        leaked.len(),
        leaked.first()
    );
    assert_eq!(
        got.len(),
        64,
        "All() yielded {} keys, want the 64 present when iteration began",
        got.len()
    );
}

