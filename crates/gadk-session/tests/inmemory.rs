#[tokio::test]
async fn test_in_memory_service_append_event_preserves_input_event_temp_state() {
    let service = InMemorySessionService::new();
    let sess = create(&service, "testapp", "testuser").await;

    let mut event = Event {
        id: "event1".into(),
        timestamp: Utc::now(),
        actions: EventActions {
            state_delta: delta(&[("temp:k1", json!("v1")), ("sk", json!("v2"))]),
            ..Default::default()
        },
        ..Default::default()
    };
    service
        .append_event(sess.as_ref(), &mut event)
        .await
        .unwrap();

    // The input event's StateDelta was not mutated in place.
    let input = event.actions.state_delta.as_ref().unwrap();
    assert!(
        input.contains_key("temp:k1"),
        "expected temp:k1 to be preserved on input event after AppendEvent, but it was removed: {input:?}"
    );
    assert_eq!(
        input.get("sk"),
        Some(&json!("v2")),
        "expected non-temp key sk to remain in input event, got: {input:?}"
    );

    // The stored event in the session has temp keys stripped.
    let stored = sess
        .events()
        .last()
        .cloned()
        .expect("expected stored event in session, got none");
    let sd = stored.actions.state_delta.unwrap_or_default();
    assert!(
        !sd.contains_key("temp:k1"),
        "expected temp:k1 to be stripped from stored event, but it still exists: {sd:?}"
    );
    assert_eq!(
        sd.get("sk"),
        Some(&json!("v2")),
        "expected non-temp key sk on stored event, got: {sd:?}"
    );
}

