// Regression guard for ADK-Go #530: `State::all` must snapshot under the lock. In Rust
// `all()` returns an owned `Vec`, so the Go map-iteration race cannot occur; the test still
// checks the observable invariants (seed key always present, count never goes backwards).
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn test_in_memory_state_all_concurrent_set() {
    const WRITERS: usize = 8;
    const ITERATIONS: usize = 200;
    let svc = Arc::new(InMemorySessionService::new());
    let sess = svc
        .create(CreateRequest {
            app_name: "app".into(),
            user_id: "user".into(),
            state: delta(&[("k0", json!(0))]),
            ..Default::default()
        })
        .await
        .unwrap();

    let start = Arc::new(tokio::sync::Barrier::new(WRITERS + 1));
    let mut handles = Vec::new();
    for w in 0..WRITERS {
        let (svc, sess, start) = (svc.clone(), sess.clone(), start.clone());
        handles.push(tokio::spawn(async move {
            start.wait().await;
            for i in 0..ITERATIONS {
                let mut ev = Event {
                    timestamp: Utc::now(),
                    actions: EventActions {
                        state_delta: delta(&[(&format!("w{w}_k{i}"), json!(i))]),
                        ..Default::default()
                    },
                    ..Default::default()
                };
                svc.append_event(sess.as_ref(), &mut ev)
                    .await
                    .unwrap_or_else(|e| panic!("AppendEvent(w{w}, i{i}) failed: {e}"));
            }
        }));
    }

    {
        let (sess, start) = (sess.clone(), start.clone());
        handles.push(tokio::spawn(async move {
            start.wait().await;
            let mut prev_count = 0;
            for _ in 0..ITERATIONS {
                let mut count = 0;
                let mut saw_seed = false;
                for (k, _) in sess.state().all() {
                    count += 1;
                    if k == "k0" {
                        saw_seed = true;
                    }
                }
                assert!(saw_seed, "All() did not yield seed key \"k0\"");
                assert!(
                    count >= prev_count,
                    "All() yielded {count} keys, want at least {prev_count} (the previous snapshot's count)"
                );
                prev_count = count;
                tokio::task::yield_now().await;
            }
        }));
    }
    for h in handles {
        h.await.unwrap();
    }
}

#[tokio::test]
async fn test_in_memory_state_all_is_snapshot() {
    let svc = InMemorySessionService::new();
    let sess = svc
        .create(CreateRequest {
            app_name: "app".into(),
            user_id: "user".into(),
            state: Some(Map::new()),
            ..Default::default()
        })
        .await
        .unwrap();
    let st = sess.state();
    for i in 0..64 {
        st.set(&format!("seed_{i:03}"), json!(i)).unwrap();
    }

    let mut got = Vec::new();
    let mut leaked = Vec::new();
    let mut first = true;
    for (k, _) in st.all() {
        if k.starts_with("injected_") {
            leaked.push(k.clone());
        }
        got.push(k);
        if first {
            // mutate hard, once, while iteration is live
            first = false;
            for i in 0..2048 {
                let _ = st.set(&format!("injected_{i:05}"), json!(i));
            }
        }
    }

    assert!(
        leaked.is_empty(),
        "All() yielded {} keys written after iteration began, e.g. {:?}",
        leaked.len(),
        leaked.first()
    );
    assert_eq!(
        got.len(),
        64,
        "All() yielded {} keys, want the 64 present when iteration began",
        got.len()
    );
}

