#[tokio::test]
async fn test_in_memory_service_append_event_copies_compaction() {
    let service = InMemorySessionService::new();
    let sess = create(&service, "app", "user").await;

    let start = Utc.with_ymd_and_hms(2026, 1, 1, 0, 0, 0).unwrap();
    let end = start + chrono::Duration::minutes(1);
    let mut event = Event {
        id: "c1".into(),
        author: "user".into(),
        ..Default::default()
    };
    event.actions.compaction = Some(EventCompaction {
        start_timestamp: start,
        end_timestamp: end,
        compacted_content: Some(Content {
            role: "model".into(),
            parts: vec![Part::from_text("summary")],
        }),
        excluded_events: Vec::new(),
    });
    service
        .append_event(sess.as_ref(), &mut event)
        .await
        .unwrap();

    // Rewrite the record through the event we still hold. A stored event must not follow.
    let mine = event.actions.compaction.as_mut().unwrap();
    mine.end_timestamp = end + chrono::Duration::hours(100);
    mine.compacted_content.as_mut().unwrap().parts[0].text = "rewritten after the append".into();

    let got = get(&service, sess.as_ref()).await;
    let stored = got.events()[0]
        .actions
        .compaction
        .clone()
        .expect("compaction was not persisted");
    assert_eq!(
        stored.end_timestamp, end,
        "stored EndTimestamp: the caller moved the covered range after the append"
    );
    assert_eq!(
        stored.compacted_content.unwrap().parts[0].text,
        "summary",
        "stored summary: the caller rewrote the stored content"
    );
}

type ActionWrite = fn(&mut Event);

// In Go this guards a fatal concurrent map read/write: `Session.Events` hands out the live
// event pointers. In Rust `Session::events` returns owned copies, so a reader writing into
// what it got cannot reach the session at all; the race is impossible by construction. The
// case is kept with the same shape (a reader mutating the newest event while appends run),
// plus a check the Go race detector stood in for: the writes never reach the canonical
// record.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn test_in_memory_service_append_event_concurrent_action_map_writes() {
    let action_maps: [(&str, ActionWrite); 3] = [
        ("ArtifactDelta", |e| {
            e.actions
                .artifact_delta
                .get_or_insert_default()
                .insert("injected".into(), 1);
        }),
        ("RequestedToolConfirmations", |e| {
            e.actions.requested_tool_confirmations.insert(
                "injected".into(),
                ToolConfirmation {
                    confirmed: true,
                    ..Default::default()
                },
            );
        }),
        ("StateDelta", |e| {
            if let Some(d) = e.actions.state_delta.as_mut() {
                d.insert("injected".into(), json!(1));
            }
        }),
    ];
    const N: usize = 20000;
    for (name, write) in action_maps {
        for delta_shape in ["with_temp", "without_temp", "nil"] {
            // A nil StateDelta cannot be written through the live event.
            if name == "StateDelta" && delta_shape == "nil" {
                continue;
            }
            let case = format!("{name}/{delta_shape}");
            let svc = Arc::new(InMemorySessionService::new());
            let live = create(&svc, "app", "u").await;
            let stop = Arc::new(AtomicBool::new(false));
            let first_write = Arc::new(tokio::sync::Notify::new());
            let reader = {
                let (live, stop, first_write) = (live.clone(), stop.clone(), first_write.clone());
                tokio::spawn(async move {
                    let mut wrote = false;
                    while !stop.load(Ordering::SeqCst) {
                        let mut evs = live.events();
                        if let Some(last) = evs.last_mut() {
                            write(last);
                            if !wrote {
                                first_write.notify_one();
                                wrote = true;
                            }
                        }
                        tokio::task::yield_now().await;
                    }
                })
            };
            for i in 0..N {
                let state_delta = match delta_shape {
                    "with_temp" => delta(&[("temp:t", json!(i)), ("k", json!(i))]),
                    "without_temp" => delta(&[("k", json!(i))]),
                    _ => None,
                };
                let mut ev = Event {
                    id: format!("e{i}"),
                    timestamp: Utc::now(),
                    actions: EventActions {
                        state_delta,
                        artifact_delta: Some(BTreeMap::from([(
                            "a".to_string(),
                            i64::try_from(i).unwrap(),
                        )])),
                        requested_tool_confirmations: BTreeMap::from([(
                            "call".to_string(),
                            ToolConfirmation::default(),
                        )]),
                        ..Default::default()
                    },
                    ..Default::default()
                };
                svc.append_event(live.as_ref(), &mut ev)
                    .await
                    .unwrap_or_else(|e| panic!("{case}: AppendEvent: {e}"));
                if i == 0 {
                    // Ensure the history writer runs before the remaining appends.
                    first_write.notified().await;
                }
            }
            stop.store(true, Ordering::SeqCst);
            reader.await.unwrap();

            let got = get(&svc, live.as_ref()).await;
            for (i, ev) in got.events().iter().enumerate() {
                let a = &ev.actions;
                assert!(
                    !a.artifact_delta
                        .as_ref()
                        .is_some_and(|m| m.contains_key("injected"))
                        && !a.requested_tool_confirmations.contains_key("injected")
                        && !a
                            .state_delta
                            .as_ref()
                            .is_some_and(|m| m.contains_key("injected")),
                    "{case}: event {i}: a reader's write reached the canonical record: {a:?}"
                );
            }
        }
    }
}

