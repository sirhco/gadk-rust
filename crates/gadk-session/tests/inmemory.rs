fn delta(pairs: &[(&str, Value)]) -> Option<Map<String, Value>> {
    Some(
        pairs
            .iter()
            .map(|(k, v)| ((*k).to_string(), v.clone()))
            .collect(),
    )
}

async fn create(svc: &InMemorySessionService, app: &str, user: &str) -> Arc<dyn Session> {
    svc.create(CreateRequest {
        app_name: app.into(),
        user_id: user.into(),
        ..Default::default()
    })
    .await
    .unwrap()
}

async fn get(svc: &InMemorySessionService, s: &dyn Session) -> Arc<dyn Session> {
    svc.get(GetRequest {
        app_name: s.app_name().into(),
        user_id: s.user_id().into(),
        session_id: s.id().into(),
        ..Default::default()
    })
    .await
    .unwrap()
}

