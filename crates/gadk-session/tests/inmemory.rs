#[tokio::test]
async fn test_in_memory_service_append_event_canonical_record_does_not_alias_live_delta() {
    // Both delta shapes matter in Go (trimTempDeltaState returns the event unchanged when it
    // strips nothing). In Rust `events()` returns owned copies, so the writes below go into
    // copies; the case still pins that neither reaches the canonical record.
    for (name, d) in [
        (
            "temp key stripped",
            delta(&[("temp:scratch", json!("x")), ("keep", json!("y"))]),
        ),
        ("nothing stripped", delta(&[("keep", json!("y"))])),
    ] {
        let service = InMemorySessionService::new();
        let live = create(&service, "app", "user").await;

        let mut event = Event {
            id: "e1".into(),
            timestamp: Utc::now(),
            actions: EventActions {
                state_delta: d,
                ..Default::default()
            },
            ..Default::default()
        };
        service
            .append_event(live.as_ref(), &mut event)
            .await
            .unwrap();

        // Write through the handle the caller still holds.
        let mut stored = live
            .events()
            .first()
            .cloned()
            .unwrap_or_else(|| panic!("{name}: expected an event on the live session handle"));
        stored
            .actions
            .state_delta
            .get_or_insert_default()
            .insert("injected".into(), json!(true));
        // And through the caller's own event.
        event
            .actions
            .state_delta
            .get_or_insert_default()
            .insert("also-injected".into(), json!(true));

        let got = get(&service, live.as_ref()).await;
        let canonical = got.events()[0]
            .actions
            .state_delta
            .clone()
            .unwrap_or_default();
        assert!(
            !canonical.contains_key("injected"),
            "{name}: canonical StateDelta = {canonical:?}: it shares the map the live handle publishes"
        );
        assert!(
            !canonical.contains_key("also-injected"),
            "{name}: canonical StateDelta = {canonical:?}: it shares the caller's map"
        );
        assert_eq!(
            canonical.get("keep"),
            Some(&json!("y")),
            "{name}: canonical StateDelta = {canonical:?}, want the non-temp key preserved"
        );
    }
}
